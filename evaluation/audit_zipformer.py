"""Research-only matched decode with the official Sherpa API, without text repair.

FLEURS occurs in this model's training list, and the cached VietSuperSpeech
references were generated by Zipformer. Neither is an independent accuracy
benchmark for this candidate. Synthetic shopping speech is a functional probe.
"""
import argparse
import hashlib
import io
import json
import time
from pathlib import Path

import av
import numpy as np
import sherpa_onnx

from evaluation.vietnamese_tone_metrics import score


def decode_audio(path):
    # The human-speech cache also contains float WAV (format 3). Use the same
    # mono/16 kHz decoding convention as the backend, never cast float bytes
    # to int16 or change the file's sample-rate label.
    chunks = []
    with av.open(io.BytesIO(path.read_bytes()), mode="r") as container:
        resampler = av.AudioResampler(format="fltp", layout="mono", rate=16000)
        for frame in container.decode(container.streams.audio[0]):
            chunks.extend(part.to_ndarray().reshape(-1) for part in resampler.resample(frame))
        chunks.extend(part.to_ndarray().reshape(-1) for part in resampler.resample(None))
    samples = np.concatenate(chunks) if chunks else np.empty(0, dtype=np.float32)
    if not np.isfinite(samples).all() or len(samples) > 60 * 16000:
        raise ValueError("Invalid or oversized research audio")
    return samples


def save(path, report):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf8")


def run(args):
    root = args.model_dir
    recognizer = sherpa_onnx.OfflineRecognizer.from_transducer(
        encoder=str(root / "encoder.int8.onnx"), decoder=str(root / "decoder.onnx"),
        joiner=str(root / "joiner.int8.onnx"), tokens=str(root / "tokens.txt"),
        num_threads=2, sample_rate=16000, feature_dim=80,
        decoding_method=args.decoding_method, max_active_paths=args.max_active_paths,
    )
    report = {"model": "hynt/Zipformer-30M-RNNT-6000h",
              "export": "sherpa-onnx-zipformer-vi-30M-int8-2026-02-09",
              "runtime": sherpa_onnx.__version__, "physical_microphone": False,
              "license": "cc-by-nc-nd-4.0", "production_switch": False,
              "input_manifest": str(args.manifest),
              "benchmark_caveats": ["FLEURS is listed in model training data",
                                    "VietSuperSpeech references are Zipformer-generated",
                                    "TTS probes are not physical-microphone tests"],
              "decoding_method": args.decoding_method,
              "max_active_paths": args.max_active_paths, "rows": [], "complete": False}
    for case in json.loads(args.manifest.read_text(encoding="utf8"))["cases"]:
        path = Path(case["file"])
        path = path if path.is_absolute() else args.manifest.parent / path
        samples = decode_audio(path)
        start = time.perf_counter()
        row = {**case, "sha256": hashlib.sha256(path.read_bytes()).hexdigest()}
        try:
            if case.get("sha256") and row["sha256"] != case["sha256"]:
                raise ValueError("Audio does not match manifest")
            stream = recognizer.create_stream()
            stream.accept_waveform(16000, samples)
            recognizer.decode_stream(stream)
            text = stream.result.text.strip()
            row.update(text=text, scores=score(case["reference"], text))
        except Exception as error:
            row["error_type"] = type(error).__name__
        row["seconds"] = round(time.perf_counter() - start, 4)
        report["rows"].append(row)
        save(args.output, report)
        print(json.dumps({"id": case["id"], "text": row.get("text"),
                          "error_type": row.get("error_type")}, ensure_ascii=False), flush=True)
    report["complete"] = True
    save(args.output, report)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--model-dir", type=Path, default=Path(".tmp/zipformer-research-20261111"))
    parser.add_argument("--decoding-method", default="greedy_search")
    parser.add_argument("--max-active-paths", type=int, default=4)
    parser.add_argument("--output", type=Path, required=True)
    run(parser.parse_args())
